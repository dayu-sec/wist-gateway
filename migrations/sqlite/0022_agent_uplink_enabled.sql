-- 数据面上送的**启用开关**（部署级，单例设置在 `agent_uplink` 上）。
--
-- 为什么需要它：启用原先只有一条**隐式**路径 —— 「该 agent 有生效工作」
-- （`api/agent_ops.rs::build_agent_uplink_grant`）。于是新装的机器注册成功却永远待命，
-- 而管理面既没有开关、也没有入口：想表达「这套网关现在开始收数据面数据」，唯一的办法是
-- 给每台派一份工作。开关把这个动作显式化，见 `docs/design/agent-uplink-enablement.md` §4.1。
--
-- 语义是**并集**（不是替代）：`enabled = 1` 或「有生效工作」都启用。
-- 代价要写清：开关打开时它**会盖过**「没有工作」，所以撤回工作不再能把某一台单独关掉
-- （要单独停就关开关，或吊销那台 agent）—— 这是刻意的粒度取舍，见设计文档 §4.1。
--
-- 默认 0：升级后行为与升级前**逐字一致**（零行为变化）—— 这是本设计的硬约束。
-- 注意：打开了它，所有已注册机器的日志 / 指标都会开始上送（页面必须把这句话说出来）。
ALTER TABLE agent_uplink ADD COLUMN enabled INTEGER NOT NULL DEFAULT 0;
